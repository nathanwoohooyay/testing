public class Greeter {
    public String greet(String name) {
        return "Hello Alice";
    }

    public String formalgreet(String name) {
        return "Very good day, " + name;
    }

    public String informalgreet(String name) {
        return "What's good " + name + "?";
    }

    public String veryformalgreet(String name) {
        return "A very very good day, " + name;
    }

    public String veryinformalgreet(String name) {
        return "Sup " + name;
    }

    public String goodbye(String name) {
        return "Goodbye, " + name;
    }
    
}
